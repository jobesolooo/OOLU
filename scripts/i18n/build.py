"""
Translations.
- scripts/i18n/strings.json: {key: [English, Dutch]} — the source of truth for keys.
- scripts/i18n/<lang>.json (it, fr, es, pt, …): {key: text}.
Run: python3 scripts/i18n/build.py [batch.json …]  → writes src/i18n/<lang>.ts
Batches (optional) are {key: [en, nl]} merged into strings.json.
"""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[2]
here = root / "scripts/i18n"
store = here / "strings.json"
data = json.loads(store.read_text()) if store.exists() else {}
for f in sys.argv[1:]:
    data.update(json.loads(pathlib.Path(f).read_text()))
store.write_text(json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True))
HEAD = "// Generated by scripts/i18n/build.py — edit the JSON in scripts/i18n, not this file.\n"
def emit(name, values, typed):
    out = [HEAD]
    out.append('import type { en } from "./en";\n\nexport const %s: Record<keyof typeof en, string> = {\n' % name if typed else "export const en = {\n")
    for k in sorted(data):
        out.append(f"  {json.dumps(k)}: {json.dumps(values[k], ensure_ascii=False)},\n")
    out.append("};\n" if typed else "} as const;\n")
    (root / f"src/i18n/{name}.ts").write_text("".join(out))
emit("en", {k: v[0] for k, v in data.items()}, False)
emit("nl", {k: v[1] for k, v in data.items()}, True)
for f in sorted(here.glob("[a-z][a-z].json")):
    lang = f.stem
    vals = json.loads(f.read_text())
    missing = [k for k in data if k not in vals]
    extra = [k for k in vals if k not in data]
    if missing: print(f"{lang}: {len(missing)} missing → English used:", ", ".join(missing[:8]))
    if extra: print(f"{lang}: {len(extra)} unknown keys ignored")
    emit(lang, {k: vals.get(k, data[k][0]) for k in data}, True)
print(len(data), "keys")
